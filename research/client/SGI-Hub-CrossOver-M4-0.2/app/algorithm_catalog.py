def find_chapters(category='全部', query=''):
    terms=query.casefold().split()
    return [c for c in chapters() if (category=='全部' or c['category']==category)
            and all(t in (' '.join((c['title'],c['summary'],c['level'],c['evidence']))+' '+
                ' '.join(a+' '+b for a,b in c['sections'])).casefold() for t in terms)]
