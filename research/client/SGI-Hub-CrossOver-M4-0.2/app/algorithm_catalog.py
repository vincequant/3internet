def attack_table():
    lines=['兵种　小 / 中 / 大队基数　训练乘数']
    for name,(bases,_,multipliers,_) in PARAMS.items():
        lines.append(f"{name}　{' / '.join(map(str,bases))}　{' / '.join(map(str,multipliers))}")
    return '\n'.join(lines)


