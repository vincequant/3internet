import types
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
APP = ROOT / 'app'


class HubSingletonTests(unittest.TestCase):
    def test_peer_pid_skips_helpers_and_self(self):
        import sys
        sys.path.insert(0, str(APP))
        from hub_singleton import peer_hub_pid, raise_existing_hub, raise_script

        listing = (
            '10 /usr/bin/grep mac_main.py\n'
            '11 /opt/homebrew/bin/python3 -B /hub/app/mac_main.py\n'
            '12 /opt/homebrew/bin/python3 -B /hub/app/wine_nav.py\n'
        )
        self.assertEqual(peer_hub_pid(me=99, listing=listing), 11)
        self.assertIsNone(peer_hub_pid(me=11, listing=listing))
        self.assertIsNone(peer_hub_pid(me=1, listing='10 /usr/bin/pgrep -lf mac_main.py\n'))
        script = raise_script(11)
        self.assertIn('unix id is 11', script)
        self.assertIn('全知情报', script)
        self.assertNotIn('name is "Python"', script)
        self.assertTrue(raise_existing_hub(11, runner=lambda _: types.SimpleNamespace(stdout='yes\n')))
        self.assertFalse(raise_existing_hub(11, runner=lambda _: types.SimpleNamespace(stdout='no\n')))
        self.assertFalse(raise_existing_hub(None, runner=lambda _: types.SimpleNamespace(stdout='yes\n')))

    def test_reload_replaces_this_process_only(self):
        import sys
        sys.path.insert(0, str(APP))
        from hub_singleton import reload_argv, reload_hub

        argv = reload_argv('/usr/bin/python3', '/hub/app/mac_main.py')
        self.assertEqual(argv[:2], ['/usr/bin/python3', '-B'])
        self.assertEqual(Path(argv[2]), Path('/hub/app/mac_main.py'))
        seen = []
        reload_hub(before=lambda: seen.append('before'), executable='/bin/py', script='/hub/app/mac_main.py',
                   execv=lambda exe, args: seen.append((exe, list(args))))
        self.assertEqual(seen[0], 'before')
        self.assertEqual(seen[1][0], '/bin/py')
        self.assertEqual(seen[1][1][:2], ['/bin/py', '-B'])
        self.assertEqual(Path(seen[1][1][2]), Path('/hub/app/mac_main.py'))
        omni = (APP / 'omni_window.py').read_text(encoding='utf-8')
        main = (APP / 'mac_main.py').read_text(encoding='utf-8')
        self.assertIn("text='刷新'", omni)
        self.assertIn("fg='#302c22'", omni)
        self.assertIn('self.version_label', omni)
        self.assertIn('def reload_hub(self):', omni)
        self.assertIn('self.on_reload', omni)
        self.assertIn('pack(side=\'right\'', omni.split("text='刷新'", 1)[1][:400])
        self.assertIn('def restart_hub():', main)
        self.assertIn('app.on_reload=restart_hub', main)
        self.assertIn('Never stop SANPK', main)
        self.assertIn('exec_reload', main)
        self.assertNotIn('os.execv', main)

    def test_mac_main_starts_again_when_raise_fails(self):
        text = (APP / 'mac_main.py').read_text(encoding='utf-8')
        self.assertIn('from hub_singleton import peer_hub_pid, raise_existing_hub', text)
        self.assertIn('原窗口没切上来，再开一个全知情报。', text)
        self.assertIn("_root/'bridge'", text)
        self.assertNotIn('请切回原窗口', text)
        self.assertNotIn('name is "Python"', text)

